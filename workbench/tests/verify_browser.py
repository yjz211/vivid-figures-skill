from pathlib import Path
import json, re
from playwright.sync_api import sync_playwright

WEB=Path(__file__).resolve().parent.parent
OUT=WEB/'verification'; OUT.mkdir(exist_ok=True)
errors=[]; checks=[]
def check(name, condition):
    checks.append({'check':name,'passed':bool(condition)})
    assert condition,name

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='C:/Program Files/Google/Chrome/Application/chrome.exe',headless=True)
    context=browser.new_context(viewport={'width':1440,'height':1080},device_scale_factor=1,accept_downloads=True)
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(WEB.joinpath('index.html').as_uri())
    page.wait_for_selector('.chart-card')
    page.locator('.chart-card img').first.wait_for()
    page.evaluate('Promise.all(Array.from(document.images).map(i => {i.loading="eager";return i.decode().catch(()=>{})}))')
    check('147 template cards loaded', page.locator('#result-count').inner_text()=='147 张')
    check('24 items per page',page.locator('.chart-card').count()==24)
    check('Desktop no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.screenshot(path=str(OUT/'desktop.png'),full_page=True)
    # Real local asset requests, not CSS placeholders.
    check('All 149 full previews and thumbnails decode', page.evaluate('''async()=>{let paths=window.VIVID_CATALOG.cards.flatMap(c=>c.previews.flatMap(p=>[p.full,p.thumb]));const ok=await Promise.all(paths.map(src=>new Promise(resolve=>{const image=new Image();image.onload=()=>resolve(image.naturalWidth>0);image.onerror=()=>resolve(false);image.src=src})));return ok.every(Boolean)&&paths.length===298;}'''))
    page.locator('[data-category="spatial"]').click()
    check('Spatial category contains 3D bar',page.locator('[data-open="advanced.grouped_bar_3d"]').count()==1)
    page.locator('#search').fill('zzzz-no-such-chart')
    check('Empty state shown',page.locator('#empty').is_visible())
    page.locator('#empty-reset').click()
    page.locator('#search').fill('radar ridgeline')
    check('English alias search',page.locator('[data-open="advanced.radar_ridgeline"]').count()==1)
    page.locator('#search').fill('不确定性')
    check('Semantic synonym search',page.locator('.chart-card').count()>0)
    page.locator('#search').fill('SHAP')
    check('SHAP matches complete composites',page.locator('[data-open="template.shap_contribution"]').count()==1)
    page.locator('#search').fill('')
    page.locator('[data-open="advanced.radar_ridgeline"]').click()
    check('Detail opens and locks page scroll',page.locator('#detail').is_visible() and page.evaluate('document.body.style.overflow')=='hidden')
    page.locator('#detail-image').evaluate('(i)=>i.decode()')
    page.screenshot(path=str(OUT/'detail.png'))
    page.locator('#code-tab').click()
    check('Complete preview source visible',len(page.locator('#source-code').inner_text())>3000)
    page.locator('#source-mode').select_option('original')
    check('Original source available', 'from gallery_theme' not in page.locator('#source-code').inner_text())
    # Intercept only clipboard to assert the exact payload; downloads use real filesystem.
    page.evaluate('navigator.clipboard.writeText=async text=>window.__copied=text')
    page.locator('#copy-code').click()
    check('Copy passes the full selected source',page.evaluate('window.__copied===document.getElementById("source-code").textContent'))
    with page.expect_download() as d:page.locator('#download-python').click()
    d.value.save_as(str(OUT/'downloaded-original.py'))
    check('Python download is not truncated', (OUT/'downloaded-original.py').stat().st_size>3000)
    with page.expect_download() as d:page.locator('#download-bundle').click()
    d.value.save_as(str(OUT/'downloaded-template.zip'))
    check('Template ZIP downloads', (OUT/'downloaded-template.zip').stat().st_size>100000)
    page.locator('#detail-favorite').click()
    page.keyboard.press('Escape')
    check('Escape closes detail',not page.locator('#detail').is_visible())
    page.locator('#favorites-tab').click()
    check('Favorites view',page.locator('.chart-card').count()==1)
    page.reload()
    check('Favorites survive reload',page.locator('#favorite-count').inner_text()=='1')
    page.locator('#sort').select_option('number')
    check('Number ordering',page.locator('.card-number').first.inner_text()=='NO.001')
    page.locator('[data-page="7"]').click()
    check('Final page contains the last templates',page.locator('.chart-card').count()==3)
    page.locator('#sort').select_option('recommended')
    page.locator('#search').fill('桑基')
    page.locator('[data-open="advanced.sankey"]').click()
    check('All Sankey outputs selectable',page.locator('[data-variant]').count()==3)
    page.locator('[data-variant="2"]').click()
    check('Third output changes image',page.locator('#detail-image').get_attribute('src').endswith('-3.png'))
    page.keyboard.press('Escape')
    page.locator('#search').fill('')
    page.set_viewport_size({'width':390,'height':844})
    page.evaluate('scrollTo(0,0)')
    page.evaluate('Promise.all(Array.from(document.images).map(i => {i.loading="eager";return i.decode().catch(()=>{})}))')
    check('Mobile has no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.screenshot(path=str(OUT/'mobile.png'),full_page=True)
    page.locator('[data-open="advanced.radar_ridgeline"]').click()
    check('Mobile modal fits viewport',page.locator('#detail').evaluate('(d)=>d.getBoundingClientRect().width<innerWidth'))
    page.screenshot(path=str(OUT/'mobile-detail.png'))
    check('No JavaScript exceptions',not errors)
    browser.close()
(OUT/'browser-results.json').write_text(json.dumps({'checks':checks,'page_errors':errors},ensure_ascii=False,indent=2),encoding='utf8')
print(json.dumps({'passed':len(checks),'errors':errors},ensure_ascii=False))
